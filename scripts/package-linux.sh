#!/usr/bin/env bash
# Packages the Linux desktop app built by `cargo build -p audiobridge-desktop --release`:
#   target/dist/AudioBridge-<ver>-linux-x86_64.tar.gz   binary + launcher entry + icon + install.sh (per-user, no root)
#   target/dist/audiobridge-<ver>-1-x86_64.pkg.tar.zst   pacman package for Arch/Omarchy (sudo pacman -U …)
#   target/dist/SHA256SUMS
# Needs bsdtar (libarchive) and zstd. Usage: scripts/package-linux.sh [path/to/AudioBridge]
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="${CARGO_TARGET_DIR:-$root/target}"
binary="${1:-$target/release/AudioBridge}"
version="$(sed -n '/^\[workspace.package\]/,/^\[/s/^version = "\(.*\)"/\1/p' "$root/Cargo.toml")"
[ -n "$version" ] || { echo "cannot read the workspace version" >&2; exit 1; }
[ -x "$binary" ] || { echo "no release binary at $binary" >&2; exit 1; }
for tool in bsdtar zstd; do
    command -v "$tool" >/dev/null || { echo "$tool is required" >&2; exit 1; }
done

dist="$target/dist"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$dist"
files="$root/packaging/linux"

# --- per-user tarball ------------------------------------------------------------------------
name="AudioBridge-$version-linux-x86_64"
mkdir -p "$work/$name"
install -m755 "$binary" "$work/$name/audiobridge"
install -m755 "$files/install.sh" "$work/$name/install.sh"
install -m644 "$files/audiobridge.desktop" "$files/audiobridge.svg" "$root/LICENSE" "$work/$name/"
tar -C "$work" --owner=0 --group=0 --numeric-owner -czf "$dist/$name.tar.gz" "$name"

# --- pacman package --------------------------------------------------------------------------
pkg="$work/pkg"
install -Dm755 "$binary" "$pkg/usr/bin/audiobridge"
install -Dm644 "$files/audiobridge.desktop" "$pkg/usr/share/applications/audiobridge.desktop"
install -Dm644 "$files/audiobridge.svg" "$pkg/usr/share/icons/hicolor/scalable/apps/audiobridge.svg"
install -Dm644 "$root/LICENSE" "$pkg/usr/share/licenses/audiobridge/LICENSE"
size="$(du -sb "$pkg/usr" | cut -f1)"
builddate="${SOURCE_DATE_EPOCH:-$(date +%s)}"
cat > "$pkg/.PKGINFO" <<EOF
# Generated by scripts/package-linux.sh
pkgname = audiobridge
pkgbase = audiobridge
pkgver = $version-1
pkgdesc = Phone as wireless headphones and microphone for the PC (PipeWire)
url = https://github.com/Lyten02/AudioBridge
builddate = $builddate
packager = AudioBridge CI
size = $size
arch = x86_64
license = MIT
depend = glibc
depend = gcc-libs
depend = pipewire
depend = wireplumber
depend = libglvnd
depend = libxkbcommon
depend = wayland
optdepend = libxcursor: X11 sessions
optdepend = libxrandr: X11 sessions
optdepend = libxi: X11 sessions
optdepend = libnotify: error notifications
optdepend = xdg-utils: open links from the window
EOF
pkgfile="audiobridge-$version-1-x86_64.pkg.tar.zst"
owner=(--uid 0 --gid 0 --uname root --gname root)
(
    cd "$pkg"
    find . -exec touch -h -d "@$builddate" {} +
    # the same file list and order makepkg uses: metadata first
    LANG=C bsdtar "${owner[@]}" -czf .MTREE --format=mtree \
        --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO usr
    LANG=C bsdtar "${owner[@]}" --no-fflags -cf - .MTREE .PKGINFO usr | zstd -q -19 -T0 -o "$dist/$pkgfile" -f
)

(cd "$dist" && sha256sum "$name.tar.gz" "$pkgfile" > SHA256SUMS)
echo "packaged:"
ls -l "$dist/$name.tar.gz" "$dist/$pkgfile"
cat "$dist/SHA256SUMS"
